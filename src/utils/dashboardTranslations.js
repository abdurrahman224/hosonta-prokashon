const textMap = new Map(dashboardTranslations)
const reverseTextMap = new Map(dashboardTranslations.map(([en, bn]) => [bn, en]))

export function translateDashboardText(text, language) {
  if (!text) return text
  const trimmed = text.trim()
  if (language === 'bn') return textMap.get(trimmed) ?? text
  return reverseTextMap.get(trimmed) ?? text
}

const originalTextNodes = new WeakMap()
const originalAttributes = new WeakMap()

function withOriginalWhitespace(original, translated) {
  const leading = original.match(/^\s*/)?.[0] || ''
  const trailing = original.match(/\s*$/)?.[0] || ''
  return `${leading}${translated}${trailing}`
}

export function applyDashboardDomTranslations(root, language) {
  if (!root) return

  const attributes = ['placeholder', 'title', 'aria-label']
  const allElements = [root, ...root.querySelectorAll('*')]

  allElements.forEach(element => {
    if (!originalAttributes.has(element)) originalAttributes.set(element, new Map())
    const attributeOriginals = originalAttributes.get(element)

    attributes.forEach(attribute => {
      if (!element.hasAttribute(attribute)) return
      if (!attributeOriginals.has(attribute)) {
        attributeOriginals.set(attribute, element.getAttribute(attribute))
      }
      const original = attributeOriginals.get(attribute)
      const translated = translateDashboardText(original, language)
      if (element.getAttribute(attribute) !== translated) {
        element.setAttribute(attribute, translated)
      }
    })

    if (
      element instanceof HTMLInputElement ||
      element instanceof HTMLTextAreaElement ||
      element instanceof HTMLSelectElement
    ) {
      if (!attributeOriginals.has('value')) {
        attributeOriginals.set('value', element.value)
      }
      const translatedValue = translateDashboardText(
        attributeOriginals.get('value'),
        language,
      )
      if (element.tagName === 'OPTION' && element.value !== translatedValue) {
        element.value = translatedValue
        element.textContent = translatedValue
      }
    }
  })

  root.querySelectorAll('option').forEach(option => {
    if (!originalTextNodes.has(option.firstChild)) {
      if (option.firstChild) {
        originalTextNodes.set(option.firstChild, option.firstChild.textContent)
      }
    }
    if (option.firstChild) {
      const original = originalTextNodes.get(option.firstChild)
      const translated = translateDashboardText(original, language)
      if (option.firstChild.textContent !== translated) {
        option.firstChild.textContent = translated
      }
    }
  })

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  while (walker.nextNode()) {
    const node = walker.currentNode
    if (!node.nodeValue || node.parentElement?.closest('script,style,textarea')) {
      continue
    }
    if (!originalTextNodes.has(node)) {
      originalTextNodes.set(node, node.nodeValue)
    }
    const original = originalTextNodes.get(node)
    const translated = translateDashboardText(original.trim(), language)
    if (translated !== original.trim()) {
      node.nodeValue = withOriginalWhitespace(original, translated)
    }
  }
}

